function tracker = setup_tracker_jpda()
% SETUP_TRACKER_JPDA Initializes a Joint Probabilistic Data Association tracker
% Ideal for dense, cluttered Indian traffic (dense market areas, chaotic junctions)
% where multiple objects (pedestrians, cows, auto-rickshaws) are close together.
%
% Output:
%   tracker - trackerJPDA object configured with 3D Constant Velocity Kalman Filter

tracker = trackerJPDA(...
    'FilterInitializationFcn', @initConstantVelocityFilter, ...
    'AssignmentThreshold', 40.0, ...
    'ConfirmationThreshold', [3 4], ...
    'DeletionThreshold', [4 5], ...
    'MaxNumTracks', 150, ...
    'MaxNumSensors', 3);

fprintf('[OK] trackerJPDA initialized for high-density / cluttered environments.\n');
end

function filter = initConstantVelocityFilter(detection)
measurement = detection.Measurement;

state = [measurement(1); 0; measurement(2); 0; measurement(3); 0];
stateCov = diag([2.0, 10.0, 2.0, 10.0, 0.5, 4.0]);
processNoise = diag([1.5, 1.5, 0.3]);

filter = trackingKF(...
    'MotionModel', '3D Constant Velocity', ...
    'State', state, ...
    'StateCovariance', stateCov, ...
    'ProcessNoise', processNoise, ...
    'MeasurementNoise', detection.MeasurementNoise);
end
