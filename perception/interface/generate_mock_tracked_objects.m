function mockList = generate_mock_tracked_objects(scenarioType, t)
% GENERATE_MOCK_TRACKED_OBJECTS Generates synthetic perception output for the 5 SIH test scenarios
% Used by AI/ML #2 (Prediction) and Full-Stack (Planning) before perception models are trained.
%
% Scenario Types:
%   1. 'unmarked_village_road'    - Cattle crossing + oncoming pushcart
%   2. 'urban_intersection'       - Auto-rickshaws + crossing pedestrians
%   3. 'highway_merge'            - Slow truck + high speed overtaking two-wheeler
%   4. 'dense_market_area'        - Pushcarts, tight pedestrians, multiple auto-rickshaws
%   5. 'cattle_crossing_event'    - Sudden stationary/slow cow in path
%
% Output:
%   mockList - struct adhering to TrackedObjectList specification

if nargin < 2
    t = 0.0;
end

switch lower(scenarioType)
    case 'cattle_crossing_event'
        objs = [
            struct('TrackID', uint32(101), 'Class', "cattle", 'ClassID', uint8(9), ...
                   'ClassConfidence', 0.95, 'Position', single([20.0, max(-3.0, 3.0 - 0.6*t), 0.0]), ...
                   'Velocity', single([0.0, -0.6, 0.0]), 'Speed', single(0.6), ...
                   'Heading', single(-90.0), 'BoundingBox3D', single([2.2, 0.9, 1.5]), ...
                   'IsConfirmed', true, 'Age', uint32(20)), ...
            struct('TrackID', uint32(102), 'Class', "auto_rickshaw", 'ClassID', uint8(4), ...
                   'ClassConfidence', 0.91, 'Position', single([12.0 + 4.0*t, -1.5, 0.0]), ...
                   'Velocity', single([4.0, 0.0, 0.0]), 'Speed', single(4.0), ...
                   'Heading', single(0.0), 'BoundingBox3D', single([2.6, 1.3, 1.7]), ...
                   'IsConfirmed', true, 'Age', uint32(35))
        ];

    case 'dense_market_area'
        objs = [
            struct('TrackID', uint32(201), 'Class', "pushcart", 'ClassID', uint8(8), ...
                   'ClassConfidence', 0.89, 'Position', single([10.0 + 0.8*t, -2.5, 0.0]), ...
                   'Velocity', single([0.8, 0.0, 0.0]), 'Speed', single(0.8), ...
                   'Heading', single(0.0), 'BoundingBox3D', single([1.8, 1.2, 1.4]), ...
                   'IsConfirmed', true, 'Age', uint32(50)), ...
            struct('TrackID', uint32(202), 'Class', "pedestrian", 'ClassID', uint8(7), ...
                   'ClassConfidence', 0.94, 'Position', single([15.0, 1.5 - 0.3*t, 0.0]), ...
                   'Velocity', single([0.0, -0.3, 0.0]), 'Speed', single(0.3), ...
                   'Heading', single(-90.0), 'BoundingBox3D', single([0.5, 0.5, 1.7]), ...
                   'IsConfirmed', true, 'Age', uint32(15)), ...
            struct('TrackID', uint32(203), 'Class', "two_wheeler", 'ClassID', uint8(5), ...
                   'ClassConfidence', 0.93, 'Position', single([8.0 + 3.5*t, 1.8, 0.0]), ...
                   'Velocity', single([3.5, 0.1, 0.0]), 'Speed', single(3.5), ...
                   'Heading', single(1.5), 'BoundingBox3D', single([1.8, 0.7, 1.2]), ...
                   'IsConfirmed', true, 'Age', uint32(40))
        ];

    otherwise % Default: mixed road
        objs = [
            struct('TrackID', uint32(1), 'Class', "auto_rickshaw", 'ClassID', uint8(4), ...
                   'ClassConfidence', 0.92, 'Position', single([15.0 + 5.0*t, 0.0, 0.0]), ...
                   'Velocity', single([5.0, 0.0, 0.0]), 'Speed', single(5.0), ...
                   'Heading', single(0.0), 'BoundingBox3D', single([2.6, 1.3, 1.7]), ...
                   'IsConfirmed', true, 'Age', uint32(30))
        ];
end

mockList.NumObjects = uint32(length(objs));
mockList.Timestamp = double(t);
mockList.Objects = objs;

end
